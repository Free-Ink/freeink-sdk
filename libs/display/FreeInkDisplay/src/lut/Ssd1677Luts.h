// knietty's deliberately aggressive one-frame differential waveform. The BW
// RAM is the target (selector bit 0) and RED RAM is the previous frame
// (selector bit 1), so entry 1 is black->white and entry 2 is white->black.
// Unchanged black/white entries remain idle. At the controller's fastest
// 5 ms/frame setting this minimizes waveform time, at the cost of weak pigment
// movement and substantial ghosting. It is never selected outside the
// TerminalTurbo profile.

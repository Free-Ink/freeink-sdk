// --- GRAY: the overlay nudge -------------------------------------------------
// Not from the manufacturer, whose panel OTP is blank and whose tables are B/W.
// Measured on a Murphy M3 at the production voltages and VCOM (tools/murphy-gray-lab
// in the firmware repo). From a clean black pixel, n frames of VSL land at:
//
//   frames    1   2   3   4   6   8  12  16
//   level %   0  13  35  58  80  88  94  98      (0 black, 100 white)
//
// The host draws every gray pixel black in the B/W page, so each nudge starts from
// black. VSH n then VSL n nets to zero: the VSH half moves nothing on a black pixel
// and pays for the VSL half. The planes select (DTM1 = LSB, DTM2 = MSB): 00 rests,
// 01 is light, 10 and 11 are dark. Everything else rests for the same 8 frames.
constexpr uint8_t MURPHY_LUT_20_GRAY[MURPHY_LUT_LEN_VCOM] = {0x01, 0x08, 0x00, 0x00, 0x00, 0x01, 0x01};
constexpr uint8_t MURPHY_LUT_21_GRAY[MURPHY_LUT_LEN_WW] = {0x01, 0x43, 0x83, 0x00, 0x00, 0x01, 0x01};  // dark
constexpr uint8_t MURPHY_LUT_22_GRAY[MURPHY_LUT_LEN_BW] = {0x01, 0x44, 0x84, 0x00, 0x00, 0x01, 0x01};  // light
constexpr uint8_t MURPHY_LUT_23_GRAY[MURPHY_LUT_LEN_WB] = {0x01, 0x43, 0x83, 0x00, 0x00, 0x01, 0x01};  // dark

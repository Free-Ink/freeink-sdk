// UC8253 waveform LUTs for the Murphy M3 (CrowPanel 3.7", 240x416). Five
// registers per bank: 0x20 VCOM, 0x21 WW, 0x22 BW, 0x23 WB, 0x24 BB — each 42
// bytes (the OEM firmware writes ten 42-byte payloads; confirmed byte-identical
// in the touch v525 dump at 0x3c23b7e0).
//
// DEFAULT is the OEM full-refresh set: three 7-byte phase groups per register —
// kick to the opposite polarity (the visible ghost-clearing inversion flash),
// a brief settle, then the destination drive. DC-balanced; this is what clears
// ghosting.
//
// FAST is the community-sdk non-flashing derivation (commit 684effb): the
// destination-drive phase alone — here run TWICE (two identical drive groups)
// for a stronger latch, which measurably reduces per-refresh ghosting on
// hardware at the cost of a slightly longer (still non-flashing) update. No inversion sweep, so residual charge
// accumulates — the driver promotes every MURPHY_GHOST_CLEAR_INTERVAL'th fast
// refresh to a DEFAULT one to flush it.
//
// ALT is the OEM's ALTERNATE bank (0f8f4f / 4f8f0f / ...), a package deal with
// the data-driven init (0x82=0x07, 0x50=0xD7) and the 0x17/0xA5 refresh
// trigger (Ghidra: FUN_42038b60 else-branch loads them to 0x20..0x24). Run
// under the mode-0 init they flash without properly latching and ghost badly
// (community-sdk 59bc0e5 hit the same failure) — the driver only ever loads
// them as part of the full alternate package (FREEINK_MURPHY_OEM_PARTIAL Fast
// path in Uc8253MurphyDriver.cpp), never under the mode-0 init.


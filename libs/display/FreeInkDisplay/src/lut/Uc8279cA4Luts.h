// Stock V1.0.3 reader "Gray3" transition waveform: one record per register
// 0x20..0x24 (the rest of each 49-byte record is zero), with 0x50 = 0x00. Each
// pixel's 2-bit code (DTM1, DTM2) selects a register: 00 -> 0x21 hold,
// 10 -> 0x22 black, 01 -> 0x23 gray, 11 -> 0x24 white-clear, as a transition
// from the frame already on the panel. Stock patches a few frame counts per
